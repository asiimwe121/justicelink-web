#!/usr/bin/env python3
"""
Build static/uganda-geo.js from the Uganda Electoral Commission "Administrative Units, July 2022" dataset
(UG-AU-DS-2022 dataset.json: country > districts > constituency > subcounty > parish > villages).

Why this exists: the old file keyed every lookup by a bare name, so namesakes were merged and ~26% of villages
were missing. This file keeps the full path (district > county > sub-county > parish > villages) as a nested
tree, so a name can never be looked up without its parents.

Usage:  python3 build_uganda_geo.py dataset.json uganda-geo.js
"""
import json, sys, collections

SRC, OUT = sys.argv[1], sys.argv[2]
data = json.load(open(SRC, encoding='utf-8'))

def disp(name):
    # Same display rule the app already uses (str.title()), so names saved in the database keep matching.
    return name.strip().title()

# district > county > sub-county > parish > set(villages). Repeated parish records (a parish split over PDF
# pages) are unioned; repeated village names inside a parish collapse to one.
tree = collections.OrderedDict()
raw_village_rows = 0
for d in data['districts']:
    D = disp(d['district'])
    for c in d['data']:
        C = disp(c['constituency'])
        for s in c['data']:
            S = disp(s['subcounty'])
            for p in s['data']:
                P = disp(p['parish'])
                bucket = tree.setdefault(D, {}).setdefault(C, {}).setdefault(S, {}).setdefault(P, set())
                for v in p['villages']:
                    raw_village_rows += 1
                    bucket.add(disp(v))

# Sort every level and fail loudly on anything that would break the "unique by path" guarantee.
def finish(node, depth):
    if depth == 4:
        return sorted(node)
    out = collections.OrderedDict()
    for k in sorted(node):
        out[k] = finish(node[k], depth + 1)
    return out
tree = finish(tree, 0)

n = collections.Counter()
for D, cs in tree.items():
    n['districts'] += 1
    for C, ss in cs.items():
        n['counties'] += 1
        for S, ps in ss.items():
            n['subCounties'] += 1
            for P, vs in ps.items():
                n['parishes'] += 1
                n['villages'] += len(vs)
                assert vs, (D, C, S, P)
assert n['districts'] == 145 and n['counties'] == 353 and n['subCounties'] == 2198, n

meta = dict(n)
meta['source'] = 'Uganda Electoral Commission, Administrative Units in Uganda, July 2022 (UG-AU-DS-2022)'
meta['rawVillageRows'] = raw_village_rows

HEADER = """// Uganda district > county > sub-county > parish > village lookup, generated by build_uganda_geo.py.
// DO NOT EDIT BY HAND. Source: %(source)s.
// %(districts)d districts, %(counties)d counties, %(subCounties)d sub-counties, %(parishes)d parishes, %(villages)d villages.
// Split out of notifications.js so that file stays small and this data is cached on its own. Loaded with defer;
// only read when a location dropdown changes.
//
// The data is a nested tree, so a place can only be reached through its own parents. Use the ugandaGeo
// functions below; there is deliberately no lookup by a bare sub-county / parish / village name (namesakes
// exist: 51 sub-county names and 537 parish names are used in more than one place).
"""

API = r"""
const ugandaGeo = (function () {
  'use strict';
  var T = ugandaGeoTree;
  var own = Object.prototype.hasOwnProperty;
  function child(o, k) { return (o && own.call(o, k)) ? o[k] : null; }
  function keys(o) { return o ? Object.keys(o) : []; }
  function union(lists) {
    var seen = Object.create(null), out = [];
    lists.forEach(function (l) { l.forEach(function (x) { if (!seen[x]) { seen[x] = 1; out.push(x); } }); });
    return out.sort();
  }

  // Counties of a district, as listed in the tree (the app's county dropdown still uses ugandaCounties).
  function counties(d) { return keys(child(T, d)); }
  // Sub-counties of one county in one district.
  function subCounties(d, c) { return keys(child(child(T, d), c)); }
  // Every county of district d that has a sub-county called s. Usually one; a few places have two
  // (e.g. Makindye Division East / West in Kampala).
  function countiesOf(d, s) {
    var dn = child(T, d), out = [];
    if (!dn) return out;
    Object.keys(dn).forEach(function (c) { if (own.call(dn[c], s)) out.push(c); });
    return out;
  }
  // Parishes of a sub-county. Pass the county when you know it. Without it, the parishes of every
  // same-named sub-county in that district are combined (only matters for those few two-county places).
  function parishes(d, c, s) {
    if (c) return keys(child(child(child(T, d), c), s));
    var cs = countiesOf(d, s);
    return cs.length === 1 ? parishes(d, cs[0], s) : union(cs.map(function (x) { return parishes(d, x, s); }));
  }
  // Villages of a parish (read-only array). Same county rule as parishes().
  function villages(d, c, s, p) {
    if (c) return child(child(child(child(T, d), c), s), p) || [];
    var cs = countiesOf(d, s);
    return cs.length === 1 ? villages(d, cs[0], s, p) : union(cs.map(function (x) { return villages(d, x, s, p); }));
  }
  // Calls fn(district, county, subCounty, parish, village) for every village in the country.
  function walk(fn) {
    Object.keys(T).forEach(function (d) {
      Object.keys(T[d]).forEach(function (c) {
        Object.keys(T[d][c]).forEach(function (s) {
          Object.keys(T[d][c][s]).forEach(function (p) {
            T[d][c][s][p].forEach(function (v) { fn(d, c, s, p, v); });
          });
        });
      });
    });
  }
  // Unique, sorted names at each level, ignoring where they sit (for search / report filters only).
  var _all = null;
  function allNames() {
    if (_all) return _all;
    var s = Object.create(null), p = Object.create(null), v = Object.create(null);
    Object.keys(T).forEach(function (d) {
      Object.keys(T[d]).forEach(function (c) {
        Object.keys(T[d][c]).forEach(function (sc) {
          s[sc] = 1;
          Object.keys(T[d][c][sc]).forEach(function (pa) {
            p[pa] = 1;
            T[d][c][sc][pa].forEach(function (vi) { v[vi] = 1; });
          });
        });
      });
    });
    _all = { subCounties: Object.keys(s).sort(), parishes: Object.keys(p).sort(), villages: Object.keys(v).sort() };
    return _all;
  }
  return { tree: T, meta: ugandaGeoMeta, counties: counties, subCounties: subCounties, countiesOf: countiesOf,
           parishes: parishes, villages: villages, walk: walk, allNames: allNames };
})();
"""

with open(OUT, 'w', encoding='utf-8') as f:
    f.write(HEADER % meta)
    f.write('const ugandaGeoMeta = ' + json.dumps(meta, separators=(',', ':')) + ';\n')
    f.write('const ugandaGeoTree = ' + json.dumps(tree, ensure_ascii=True, separators=(',', ':')) + ';\n')
    f.write(API)

print('wrote', OUT, dict(n), 'raw village rows', raw_village_rows)
